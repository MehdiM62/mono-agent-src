// @vitest-environment jsdom
import React from 'react'
import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'
import '@testing-library/jest-dom/vitest'
import { render, screen, fireEvent, waitFor, cleanup } from '@testing-library/react'
import ApplicationDetailModal from './ApplicationDetailModal.jsx'
import * as WailsApp from '../../wailsjs/go/main/App'
import { mockApplicationDetail, mockApplicationAssets } from './fixtures.js'

vi.mock('../../wailsjs/go/main/App', () => ({
  OpenURL: vi.fn(),
  GetApplicationAssets: vi.fn(),
  GetProfileDocumentData: vi.fn(() => Promise.resolve('data:application/pdf;base64,JVBERi0=')),
  GetProfileDocumentText: vi.fn(() => Promise.resolve('Mock document text content')),
  OpenPathWithOS: vi.fn(),
}))

afterEach(() => {
  cleanup()
  vi.restoreAllMocks()
})

describe('ApplicationDetailModal', () => {
  it('renders all sections in order with Contract B assets fixture', async () => {
    WailsApp.GetApplicationAssets.mockResolvedValue(mockApplicationAssets)

    render(
      <ApplicationDetailModal
        applicationId="app-test-1"
        detail={mockApplicationDetail}
        onClose={vi.fn()}
      />
    )

    // 1. Header
    expect(screen.getByText('Lead Systems Architect')).toBeInTheDocument()
    expect(screen.getByRole('status', { name: /Status: awaiting submit/i })).toBeInTheDocument()

    // Wait for assets to load
    await waitFor(() => {
      // 2. Posting
      expect(screen.getByText(/We are seeking a Lead Systems Architect/)).toBeInTheDocument()
    })

    // 3. Documents
    expect(screen.getByText('CV_Systems_Architect.pdf')).toBeInTheDocument()
    expect(screen.getAllByRole('status', { name: /Attached to application/i })).toHaveLength(2)

    // 4. Filled form
    expect(screen.getByAltText('Filled form screenshot')).toBeInTheDocument()
    expect(screen.getByText('Full Legal Name')).toBeInTheDocument()
    expect(screen.getByRole('status', { name: /Generated by AI/i })).toBeInTheDocument()

    // 5. People & messages
    expect(screen.getByText('Sarah Connor')).toBeInTheDocument()
    expect(screen.getByText(/Interview inquiry/)).toBeInTheDocument()

    // 6. Tasks
    expect(screen.getByText('Review OmniCorp submission form in parked browser tab')).toBeInTheDocument()

    // 7. Status history
    expect(screen.getByText('(created)')).toBeInTheDocument()
    expect(screen.getByText('awaiting_submit')).toBeInTheDocument()

    // 8. Coder task
    expect(screen.getByRole('status', { name: /Coder task status: needs user/i })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /Open chat in coder bubble/i })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /Reopen tab \(coming with the apply task\)/i })).toBeDisabled()
    expect(screen.getByRole('button', { name: /Refill \(coming with the apply task\)/i })).toBeDisabled()
  })

  it('revert-proof: guards against missing GetApplicationAssets binding and renders empty state without crashing', async () => {
    // Simulate missing Wails binding (not yet created on Go side)
    const orig = WailsApp.GetApplicationAssets
    delete WailsApp.GetApplicationAssets

    try {
      render(
        <ApplicationDetailModal
          applicationId="app-test-1"
          detail={mockApplicationDetail}
          onClose={vi.fn()}
        />
      )

      // Header from detail still renders
      expect(screen.getByText('Lead Systems Architect')).toBeInTheDocument()
      expect(screen.getByRole('status', { name: /Status: awaiting submit/i })).toBeInTheDocument()

      // Empty states for sections
      await waitFor(() => {
        expect(screen.getByText('No captured posting text available.')).toBeInTheDocument()
      })
      expect(screen.getByText('No documents attached or generated for this application.')).toBeInTheDocument()
      expect(screen.getByText('No filled form data available.')).toBeInTheDocument()
      expect(screen.getByText('No people or messages linked to this application.')).toBeInTheDocument()
      expect(screen.getByText('No tasks linked to this application.')).toBeInTheDocument()
      expect(screen.getByText('No active coder task.')).toBeInTheDocument()
    } finally {
      WailsApp.GetApplicationAssets = orig
    }
  })

  it('handles GetApplicationAssets rejection gracefully without crashing', async () => {
    WailsApp.GetApplicationAssets.mockRejectedValue(new Error('connection failed'))

    render(
      <ApplicationDetailModal
        applicationId="app-test-1"
        detail={mockApplicationDetail}
        onClose={vi.fn()}
      />
    )

    expect(screen.getByText('Lead Systems Architect')).toBeInTheDocument()
    await waitFor(() => {
      expect(screen.getByText('No captured posting text available.')).toBeInTheDocument()
    })
    expect(screen.getByText('No documents attached or generated for this application.')).toBeInTheDocument()
  })

  it('opens FileViewerModal when clicking preview on a document', async () => {
    WailsApp.GetApplicationAssets.mockResolvedValue(mockApplicationAssets)

    render(
      <ApplicationDetailModal
        applicationId="app-test-1"
        detail={mockApplicationDetail}
        onClose={vi.fn()}
      />
    )

    await waitFor(() => {
      expect(screen.getByText('CV_Systems_Architect.pdf')).toBeInTheDocument()
    })

    const previewButtons = screen.getAllByRole('button', { name: /Preview/i })
    fireEvent.click(previewButtons[0])

    // FileViewerModal dialog appears
    await waitFor(() => {
      expect(screen.getByRole('dialog', { name: /File preview/i })).toBeInTheDocument()
    })
  })

  it('calls onClose when close button clicked or Escape pressed', () => {
    const onClose = vi.fn()
    render(
      <ApplicationDetailModal
        applicationId="app-test-1"
        detail={mockApplicationDetail}
        initialAssets={mockApplicationAssets}
        onClose={onClose}
      />
    )

    const closeBtn = screen.getByRole('button', { name: 'Close dialog' })
    fireEvent.click(closeBtn)
    expect(onClose).toHaveBeenCalledTimes(1)

    // Test Escape key
    fireEvent.keyDown(window, { key: 'Escape' })
    expect(onClose).toHaveBeenCalledTimes(2)
  })
})
