// openWorkflowStore returns the workflow store shared by the CLI and the
// desktop app: JSON files under ~/.monoagent/workflows plus the SQLite
// database, so a workflow made by either side shows up on the other.
func openWorkflowStore(db *storage.Database) *workflow.HybridWorkflowStore {
	sqlStore := workflow.NewSQLiteWorkflowStore(db.DB)
	dir := expandPath("~/.monoagent/workflows")
	fileStore, err := workflow.NewWorkflowFileStore(dir)
	if err != nil {
		// No usable workflow directory: keep the same return type, backed by
		// SQLite alone.
		return withGrantTierRefresh(db, workflow.NewHybridWorkflowStore(nil, sqlStore))
	}
	// Workflows saved file-only (the desktop editor, older CLI versions)
	// get their SQLite rows backfilled; cheap after the first run.
	synced, _ := syncFileWorkflowsToSQL(context.Background(), db.DB, dir)
	store := withGrantTierRefresh(db, workflow.NewHybridWorkflowStore(fileStore, sqlStore))
	for _, id := range synced {
		raiseGrantTiersForWorkflow(context.Background(), db, store.GetWorkflow, id)
	}
	return store
}

// withGrantTierRefresh makes every save through store re-derive the tiers
// of the saved workflow's org grants (#284).
func withGrantTierRefresh(db *storage.Database, store *workflow.HybridWorkflowStore) *workflow.HybridWorkflowStore {
	store.SetOnSaved(func(ctx context.Context, id string) {
		raiseGrantTiersForWorkflow(ctx, db, store.GetWorkflow, id)
	})
	return store
}

// createOrOverwriteWorkflowAtomically persists wf (metadata + nodes +
// connections) via store so the operation either fully succeeds or leaves
// the store exactly as it was before the call — never a partial mix of old
// and new state. Shared by `workflow import` and `workflow templates use`,
// the two commands that create a workflow's full node/connection set in
// one shot (as opposed to the editing commands, which mutate an existing
// workflow's nodes or connections independently and don't create a fresh
// workflow record at all).
//
// Callers must have already: finalized every id on wf/wf.Nodes/
// wf.Connections (this function does not mint ids — a caller-side retry
// after a failure needs stable ids to know what it itself created), and
// validated wf.Connections against wf.Nodes via
// workflow.ValidateConnectionsAgainstNodes. That validation is intentionally
// the caller's job, not this function's: the common failure (a dangling
// connection reference) should be caught in memory, before this function —
// and therefore the store — is ever invoked at all.
//
// If overwrite is true and a workflow already exists at wf.ID, its full
// prior state is captured before writing anything and restored verbatim on
// any failure. Otherwise a failure is compensated by deleting whatever was
// partially created — safe specifically because a non-overwrite id is
// always freshly generated by the caller and can never collide with
// pre-existing data.
func createOrOverwriteWorkflowAtomically(ctx context.Context, store *workflow.HybridWorkflowStore, wf *workflow.Workflow, overwrite bool) error {
	var previous *workflow.Workflow
	if overwrite {
		previous, _ = store.GetWorkflow(ctx, wf.ID) // nil if nothing exists yet at this id
	}

	persistErr := func() error {
		if err := store.CreateWorkflow(ctx, wf); err != nil {
			return fmt.Errorf("save workflow: %w", err)
		}
		for i := range wf.Nodes {
			if wf.Nodes[i].Config != nil {
				if err := wf.Nodes[i].MarshalConfig(); err != nil {
					return fmt.Errorf("marshal node config: %w", err)
				}
			}
		}
		if err := store.SaveWorkflowNodes(ctx, wf.ID, wf.Nodes); err != nil {
			return fmt.Errorf("save nodes: %w", err)
		}
		if err := store.SaveWorkflowConnections(ctx, wf.ID, wf.Connections); err != nil {
			return fmt.Errorf("save connections: %w", err)
		}
		return nil
	}()
	if persistErr == nil {
		return nil
	}

	if previous != nil {
		if restoreErr := restoreWorkflowSnapshot(ctx, store, previous); restoreErr != nil {
			return fmt.Errorf("%w (restoring the previous version also failed: %v — workflow %s may be in a partially-modified state; inspect it manually)",
				persistErr, restoreErr, wf.ID)
		}
		return fmt.Errorf("%w (the previous version of workflow %s was restored, unchanged)", persistErr, wf.ID)
	}
	if cleanupErr := store.DeleteWorkflow(ctx, wf.ID); cleanupErr != nil {
		return fmt.Errorf("%w (additionally, cleaning up the partially-created workflow failed: %v — a leftover workflow %s may still exist; inspect ~/.monoagent manually)",
			persistErr, cleanupErr, wf.ID)
	}
	return persistErr
}

// restoreWorkflowSnapshot re-persists a previously captured *workflow.Workflow
// (metadata + nodes + connections) — used by createOrOverwriteWorkflowAtomically
// to put an existing workflow back the way it was after a failed overwrite.
// This is a logical, not a byte-for-byte, restoration: node configs are
// re-marshaled and rows re-inserted, so incidental metadata (e.g.
// updated_at) can legitimately differ from the original, but every node,
// connection, and config value is restored unchanged.
func restoreWorkflowSnapshot(ctx context.Context, store *workflow.HybridWorkflowStore, snapshot *workflow.Workflow) error {
	wf := *snapshot
	if err := store.CreateWorkflow(ctx, &wf); err != nil {
		return fmt.Errorf("restore workflow metadata: %w", err)
	}
	nodes := append([]workflow.WorkflowNode(nil), snapshot.Nodes...)
	for i := range nodes {
		if nodes[i].Config != nil {
			if err := nodes[i].MarshalConfig(); err != nil {
				return fmt.Errorf("restore: marshal node config: %w", err)
			}
		}
	}
	if err := store.SaveWorkflowNodes(ctx, wf.ID, nodes); err != nil {
		return fmt.Errorf("restore nodes: %w", err)
	}
	if err := store.SaveWorkflowConnections(ctx, wf.ID, snapshot.Connections); err != nil {
		return fmt.Errorf("restore connections: %w", err)
	}
	return nil
}

// buildEngine constructs a fully wired WorkflowEngine suitable for CLI use.
// It creates its own scheduler (no action executor or store needed for workflow triggers).
// The returned cleanup func is currently a no-op placeholder kept for the
// engine lifecycle contract; callers should defer it alongside
// engine.Stop().
func buildEngine(cfg *globalConfig, allowAllProfiles bool) (*workflow.WorkflowEngine, func(), error) {
	db, err := initDB(cfg)
	if err != nil {
		return nil, func() {}, fmt.Errorf("open database: %w", err)
	}

	registry := buildNodeRegistry(cfg.Verbose, db.DB)

	logger := logging.Zerolog()
	if cfg.Verbose {
		logger = logger.Level(zerolog.TraceLevel)
	}

	// Set up browser session provider, bot registry, and config manager
	// so browser/social nodes work in workflows. Chrome extension only —
	// no Rod/Chromium fallback, sharing another local process's connection
	// when one already exists (e.g. the daemon). The bridge is connected
	// lazily on the first browser-node GetPage: connecting eagerly blocked
	// every engine command (workflow run/activate/daemon) for up to ~60s
	// and launched the user's real Chrome even for browserless workflows.
	extLogger := logger.With().Str("component", "extension").Logger()
	sessionProvider := &lazyBrowserSessionProvider{logger: extLogger, defaultProfile: cfg.ProfileID}
	nodes.SetGlobalSessionProvider(sessionProvider)
	nodes.SetGlobalBotRegistry(&cliBotRegistry{})
	nodes.SetGlobalCredentialStore(connections.NewStore(db.DB))

	cfgLogger := logging.Zerolog()
	cfgStore := cfgpkg.ConfigStore(&cfgpkg.DBConfigStore{DB: db})
	rawCfgMgr := cfgpkg.NewConfigManager(expandPath("~/.monoagent/configs"), cfgStore, cfgLogger)
	nodes.SetGlobalConfigMgr(&cfgpkg.ConfigManagerAdapter{Mgr: rawCfgMgr})

	sched := scheduler.NewScheduler(logger)
	sched.Start()

	engCfg := workflow.EngineConfig{
		MaxConcurrent:    5,
		QueueCapacity:    1000,
		PruneInterval:    time.Hour,
		MaxExecHistory:   500,
		ProfileID:        cfg.ProfileID,
		AllowAllProfiles: allowAllProfiles,
	}

	hybridStore := openWorkflowStore(db)
	engine := workflow.NewWorkflowEngineWithStore(hybridStore, db.DB, sched, registry, engCfg, logger)
	return engine, func() {
		sessionProvider.Close()
		nodes.CloseHealthObservers()
	}, nil
}

// lazyBrowserSessionProvider implements nodes.SessionProvider by connecting
// the Chrome extension bridge on first use instead of at engine build time.
// Browser nodes call GetPage when they execute, so the connect sequence
// runs only for workflows that actually contain a browser node.
//
// Each GetPage is narrowed to the browser bound to the run's profile: the
// execution's profile id rides ctx (WorkflowEngine.runExecution), so a
// daemon running many profiles' workflows sends each one to its own
// browser. Only building the shared bridge is serialised; waiting for a
// profile's browser is not, so one profile's slow browser never holds up
// another's run.
type lazyBrowserSessionProvider struct {
	logger         zerolog.Logger
	defaultProfile string // the engine's profile, for a ctx that carries none

	// setup and ensure default to setupExtensionBridge (3s wait) and
	// ensureExtensionConnected; tests replace them.
	setup  func() browserpkg.ExtensionBridge
	ensure func(connChecker, time.Duration) error

	mu     sync.Mutex
	bridge browserpkg.ExtensionBridge
}

func (p *lazyBrowserSessionProvider) base() browserpkg.ExtensionBridge {
	p.mu.Lock()
	defer p.mu.Unlock()
	if p.bridge == nil {
		if p.setup != nil {
			p.bridge = p.setup()
		} else {
			p.bridge = setupExtensionBridge(p.logger, 3*time.Second)
		}
	}
	return p.bridge
}

func (p *lazyBrowserSessionProvider) GetPage(ctx context.Context, platform, username string) (browserpkg.PageInterface, error) {
	profileID, ok := vault.ProfileIDInContext(ctx)
	if !ok {
		profileID = p.defaultProfile
	}
	bridge := bridgeForProfile(p.base(), profileID)
	ensure := p.ensure
	if ensure == nil {
		ensure = ensureExtensionConnected
	}
	// No throwaway automation browser. When this profile's browser is not
	// attached, launch the user's real Chrome (same mechanism as `login`)
	// and wait for it.
	if err := ensure(bridge, 30*time.Second); err != nil {
		return nil, fmt.Errorf("browser session: %w", err)
	}
	return (&browserpkg.HybridSessionProvider{ExtBridge: bridge, Logger: p.logger}).GetPage(ctx, platform, username)
}

// Close matches the cleanup signature buildEngine hands back. There is
// nothing to tear down: HybridSessionProvider.Close is a no-op, and the
// extension server (when the lazy connect ever ran) is a process-wide
// singleton on a fixed port that outlives individual engine runs.
func (p *lazyBrowserSessionProvider) Close() {}

